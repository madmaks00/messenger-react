export class EmojiService {
  public static getCategories(): Record<string, string[]> {
    return {
      Recent: this.getRecent(),
      ...EMOJI_DATABASE,
    };
  }

  public static getRecent(): string[] {
    try {
      const raw = localStorage.getItem(RECENT_KEY);
      return raw ? JSON.parse(raw) : ['👍', '❤️', '🔥', '😂', '👏', '🎉', '😊', '😍'];
    } catch {
      return ['👍', '❤️', '🔥', '😂'];
    }
  }

  public static addToRecent(emoji: string): void {
    if (!emoji) return;
    const recent = this.getRecent().filter((e) => e !== emoji);
    recent.unshift(emoji);
    if (recent.length > 30) recent.pop();
    try {
      localStorage.setItem(RECENT_KEY, JSON.stringify(recent));
    } catch {}
  }
}